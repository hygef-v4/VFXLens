import assert from 'node:assert/strict';
import {animate} from 'animejs';
import {gsap} from 'gsap';
import initJolt from 'jolt-physics';
import {mix} from 'motion';
import {BloomEffect} from 'postprocessing';
import * as THREE from 'three';
import {PhysicalPathTracingMaterial} from 'three-gpu-pathtracer';
import {MeshBVH} from 'three-mesh-bvh';
import {ParticleSystem} from 'three.quarks';

const geometry = new THREE.BoxGeometry(1, 1, 1);
const bvh = new MeshBVH(geometry);
assert.ok(bvh.raycastFirst(new THREE.Ray(new THREE.Vector3(0, 0, 3), new THREE.Vector3(0, 0, -1))));
assert.equal(typeof PhysicalPathTracingMaterial, 'function');
assert.equal(typeof ParticleSystem, 'function');
const bloom = new BloomEffect();
assert.ok(bloom);
bloom.dispose();
geometry.dispose();

const target = {x: 0};
const animation = animate(target, {x: 100, duration: 1000, ease: 'linear', autoplay: false});
animation.seek(500);
assert.ok(Math.abs(target.x - 50) < 0.01);
animation.cancel();
const gsapTarget = {x: 0};
const tween = gsap.to(gsapTarget, {x: 100, duration: 1, ease: 'none', paused: true});
tween.progress(0.5);
assert.equal(gsapTarget.x, 50);
tween.kill();
assert.equal(mix(0, 100)(0.5), 50);

const Jolt = await initJolt();
const vector = new Jolt.Vec3(1, 2, 3);
assert.equal(vector.GetY(), 2);
Jolt.destroy(vector);
console.log('Passed: Three.js geometry/BVH, pathtracer/particle exports, bloom setup, animation seek, Motion mix and Jolt WASM.');
console.log('Browser rendering, model inference and full particle/pathtracing scenes require their own production checks.');
gsap.ticker.sleep();
